"""Writes sw.js with the full list of files to keep offline, and a version stamp from their contents.
Run after any change:  python tools/build.py"""
import hashlib
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {"tools", ".git", ".github"}
SKIP_FILES = {"sw.js", "README.md", "LICENSE", ".nojekyll"}

files = []
h = hashlib.sha256()
for d, dirs, fs in os.walk(ROOT):
    dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
    for f in sorted(fs):
        rel = os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, "/")
        if f in SKIP_FILES and "/" not in rel:
            continue
        files.append(rel)
        with open(os.path.join(d, f), "rb") as fh:
            h.update(rel.encode() + fh.read())
ver = h.hexdigest()[:10]
lst = ",\n  ".join('"./%s"' % f for f in ["", *files] if True).replace('"./"', '"./"')
sw = """/* Generated by tools/build.py. Keeps the whole guide on the phone so it works with no signal. */
const CACHE = "dpfg-%s";
const FILES = [
  %s
];
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("dpfg-") && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => caches.match("./index.html"))));
});
""" % (ver, lst)
with open(os.path.join(ROOT, "sw.js"), "w") as f:
    f.write(sw)
print("sw.js: %d files, cache dpfg-%s" % (len(files) + 1, ver))
